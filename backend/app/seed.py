def seed(reset: bool = False) -> None:
    if reset:
        from .db import Base
        Base.metadata.drop_all(engine)
    init_db()

    with SessionLocal() as db:
        if db.scalar(select(LegalEntity).limit(1)):
            print("В базе уже есть данные. Используйте --reset для пересоздания.")
            return

        entities = [LegalEntity(**e) for e in ENTITIES]
        db.add_all(entities)
        db.flush()
        by_short = {e.short_name: e for e in entities}

        for spec in INBOXES:
            owner = by_short["ООО «Ромашка»"] if "romashka" in spec["email"] \
                else by_short["АО «Василёк»"]
            db.add(Inbox(legal_entity_id=owner.id, **spec))

        for spec in SERVICES:
            db.add(Service(legal_entity_id=by_short["ООО «Ромашка»"].id, **spec))

        for spec in TEMPLATES:
            t = ResponseTemplate(**spec)
            t.placeholders = find_placeholders(t.body)
            db.add(t)
        db.flush()

        now = utcnow()
        for spec in DEMO_REQUESTS:
            create_request(
                db,
                inbox_email=spec["inbox"], requester_email=spec["email"],
                requester_name=spec["name"], subject_line=spec["subject"],
                body_text=spec["body"],
                received_at=now - timedelta(days=spec["days_ago"], hours=3),
                channel=Channel.EMAIL, analyze=True, use_llm=False, actor="seed",
            )
        db.commit()

        # Немного разнообразия по статусам, чтобы реестр выглядел как рабочий.
        rows = list(db.scalars(select(Request).order_by(Request.id)))
        if len(rows) >= 6:
            set_status(db, rows[0], Status.IN_PROGRESS, actor="seed")
            set_status(db, rows[2], Status.IN_PROGRESS, actor="seed")
            set_status(db, rows[5], Status.ANSWERED, actor="seed")
            rows[0].assignee = "Зимина Т. А."
            rows[2].assignee = "Зимина Т. А."
        db.commit()

        print(f"Готово: {len(entities)} юрлица, {len(INBOXES)} ящиков, "
              f"{len(SERVICES)} сервисов, {len(TEMPLATES)} типовых ответов, "
              f"{len(DEMO_REQUESTS)} обращений.")


if __name__ == "__main__":
    seed(reset="--reset" in sys.argv)
